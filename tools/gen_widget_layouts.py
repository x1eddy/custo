#!/usr/bin/env python3
"""
Generates the per-font RemoteViews layouts for Custo's widgets.

RemoteViews can't set a typeface at runtime, so every clock face needs one layout per font.
This writes:
  * the bundled-font variants (round, tech, hand, elegant) of the original six layout families,
    copied from the *_sans.xml layouts with the font swapped,
  * the newer clock faces (flip, neon, vertical) for all ten fonts,
  * text_<font>.xml for Glance text in a bundled font,
  * app/src/main/java/app/custo/feature/widgets/FontLayouts.kt, the lookup tables.

Run from the repo root:  python3 tools/gen_widget_layouts.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LAYOUT = os.path.join(ROOT, "app/src/main/res/layout")
KT = os.path.join(ROOT, "app/src/main/java/app/custo/feature/widgets/FontLayouts.kt")

# name -> (fontFamily, can bold, all caps for small labels)
FONTS = {
    "sans": ("sans-serif", True, False),
    "serif": ("serif", True, False),
    "mono": ("monospace", True, False),
    "cursive": ("cursive", True, False),
    "pixel": ("@font/custo_pixel", False, False),
    "heavy": ("@font/custo_heavy", False, True),
    "round": ("@font/custo_round", False, False),
    "tech": ("@font/custo_tech", False, False),
    "hand": ("@font/custo_hand", False, False),
    "elegant": ("@font/custo_elegant", False, False),
}
ORDER = list(FONTS)  # same order as the WidgetFont enum
NEW_FONTS = ["round", "tech", "hand", "elegant"]
ENUM = {"round": "ROUNDED"}  # file suffix -> WidgetFont name, where they differ
FAMILIES = ["chrono", "clock_big", "clock_hour", "clock_minimal", "clock_stacked", "world_row"]
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_widget_layouts.py. Edit the script, not this file. -->\n'


def write(name, body):
    with open(os.path.join(LAYOUT, name + ".xml"), "w", encoding="utf-8") as f:
        f.write(body)


def attrs(font, bold=False, caps=False):
    fam, can_bold, heavy_caps = FONTS[font]
    a = f'android:fontFamily="{fam}"'
    if bold and can_bold:
        a += ' android:textStyle="bold"'
    if caps and heavy_caps:
        a += ' android:textAllCaps="true"'
    return a


def from_sans(family, font):
    src = open(os.path.join(LAYOUT, family + "_sans.xml"), encoding="utf-8").read()
    src = src.replace(' android:textStyle="bold"', "")
    src = src.replace('android:fontFamily="sans-serif"', 'android:fontFamily="%s"' % FONTS[font][0])
    src = re.sub(r'^<\?xml[^>]*>\n', HEADER, src)
    write(f"{family}_{font}", src)


def text_layout(font):
    write(f"text_{font}", HEADER + f'''<TextView xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/text" android:layout_width="match_parent" android:layout_height="wrap_content"
    {attrs(font)} android:ellipsize="end" android:includeFontPadding="false" />
''')


def flip(font):
    card = lambda vid, f12, f24, margin: f'''        <FrameLayout android:layout_width="wrap_content" android:layout_height="wrap_content"{margin}
            android:background="@drawable/flip_card" android:paddingHorizontal="6dp" android:paddingVertical="2dp">
            <TextClock android:id="@+id/{vid}" android:layout_width="wrap_content" android:layout_height="wrap_content"
                android:layout_gravity="center" android:gravity="center" android:format12Hour="{f12}" android:format24Hour="{f24}"
                {attrs(font, bold=True)} android:textSize="52sp" android:includeFontPadding="false" />
            <FrameLayout android:layout_width="match_parent" android:layout_height="1dp" android:layout_gravity="center_vertical"
                android:background="#66000000" />
        </FrameLayout>
'''
    write(f"clock_flip_{font}", HEADER + f'''<!-- Split-flap clock: hours and minutes on two dark cards with a hinge line. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/root" android:layout_width="match_parent" android:layout_height="match_parent"
    android:gravity="center" android:orientation="vertical">
    <LinearLayout android:layout_width="wrap_content" android:layout_height="wrap_content" android:orientation="horizontal">
{card("time", "hh", "HH", "")}{card("time2", "mm", "mm", ' android:layout_marginStart="5dp"')}    </LinearLayout>
    <TextClock android:id="@+id/date" android:layout_width="wrap_content" android:layout_height="wrap_content" android:layout_marginTop="4dp"
        android:format12Hour="EEE d MMM" android:format24Hour="EEE d MMM" {attrs(font, caps=True)} android:textSize="13sp" android:alpha="0.85" />
</LinearLayout>
''')


def neon(font):
    write(f"clock_neon_{font}", HEADER + f'''<!-- Neon sign: the time with a wide soft glow (padding keeps the glow from being clipped). -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/root" android:layout_width="match_parent" android:layout_height="match_parent"
    android:gravity="center" android:orientation="vertical">
    <TextClock android:id="@+id/time" android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:paddingHorizontal="10dp" android:paddingVertical="3dp"
        android:format12Hour="h:mm" android:format24Hour="HH:mm" {attrs(font)} android:textSize="52sp" android:includeFontPadding="false"
        android:shadowColor="#E6FFFFFF" android:shadowDx="0" android:shadowDy="0" android:shadowRadius="14" />
    <TextClock android:id="@+id/date" android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:paddingHorizontal="10dp"
        android:format12Hour="EEE d MMM" android:format24Hour="EEE d MMM" {attrs(font)} android:textSize="13sp" android:textAllCaps="true"
        android:letterSpacing="0.12" android:shadowColor="#B3FFFFFF" android:shadowDx="0" android:shadowDy="0" android:shadowRadius="8" />
</LinearLayout>
''')


def vertical(font):
    # ems="1" + letter spacing makes each two-digit field wrap to one digit per line.
    digits = lambda vid, f12, f24, extra: f'''    <TextClock android:id="@+id/{vid}" android:layout_width="wrap_content" android:layout_height="wrap_content"
        android:ems="1" android:letterSpacing="0.35" android:gravity="center" android:format12Hour="{f12}" android:format24Hour="{f24}"
        {attrs(font, bold=True)} android:textSize="34sp" android:includeFontPadding="false" android:lineSpacingMultiplier="0.9"{extra} />
'''
    write(f"clock_vertical_{font}", HEADER + f'''<!-- Narrow column: hour digits over minute digits, one digit per line, weekday underneath. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/root" android:layout_width="match_parent" android:layout_height="match_parent"
    android:gravity="center" android:orientation="vertical">
{digits("time", "hh", "HH", "")}{digits("time2", "mm", "mm", ' android:alpha="0.7" android:layout_marginTop="2dp"')}    <TextClock android:id="@+id/date" android:layout_width="wrap_content" android:layout_height="wrap_content" android:layout_marginTop="4dp"
        android:format12Hour="EEE" android:format24Hour="EEE" {attrs(font)} android:textSize="11sp" android:textAllCaps="true" android:letterSpacing="0.15" />
</LinearLayout>
''')


def led():
    write("clock_led", HEADER + f'''<!-- LED panel: unlit "88:88" segments behind the lit time, in the pixel face. -->
<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@+id/root" android:layout_width="match_parent" android:layout_height="match_parent"
    android:gravity="center" android:orientation="vertical">
    <FrameLayout android:layout_width="wrap_content" android:layout_height="wrap_content">
        <TextView android:id="@+id/ghost" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:layout_gravity="center" android:text="@string/led_ghost" {attrs("pixel")} android:textSize="48sp"
            android:includeFontPadding="false" android:alpha="0.13" android:paddingHorizontal="4dp" />
        <TextClock android:id="@+id/time" android:layout_width="wrap_content" android:layout_height="wrap_content"
            android:layout_gravity="center" android:format12Hour="hh:mm" android:format24Hour="HH:mm" {attrs("pixel")} android:textSize="48sp"
            android:includeFontPadding="false" android:paddingHorizontal="4dp"
            android:shadowColor="#99FFFFFF" android:shadowDx="0" android:shadowDy="0" android:shadowRadius="6" />
    </FrameLayout>
    <TextClock android:id="@+id/date" android:layout_width="wrap_content" android:layout_height="wrap_content" android:layout_marginTop="2dp"
        android:format12Hour="EEE dd MMM" android:format24Hour="EEE dd MMM" {attrs("pixel")} android:textSize="13sp" android:textAllCaps="true"
        android:letterSpacing="0.1" android:alpha="0.85" />
</LinearLayout>
''')


def kotlin():
    def arr(prefix, fonts):
        return ", ".join(f"R.layout.{prefix}_{f}" for f in fonts)
    extra = ",\n".join(f"            R.layout.{fam}_sans to intArrayOf({arr(fam, NEW_FONTS)})" for fam in FAMILIES)
    text = ",\n".join(f"            WidgetFont.{ENUM.get(f, f.upper())} to R.layout.text_{f}" for f in ORDER if f in ("pixel", "heavy") + tuple(NEW_FONTS))
    out = f'''// Generated by tools/gen_widget_layouts.py. Edit the script, not this file.
package app.custo.feature.widgets

import app.custo.R

/** RemoteViews layouts per widget font (RemoteViews can't change a TextView's typeface at runtime). */
internal object FontLayouts {{
    /** The bundled-font variants of each original layout family, keyed by its sans layout, in [WidgetFont] order from ROUNDED. */
    private val extra: Map<Int, IntArray> by lazy {{
        mapOf(
{extra},
        )
    }}

    /** [font]'s variant of the family whose sans layout is [sans] (for fonts added after HEAVY). */
    fun extra(sans: Int, font: WidgetFont): Int =
        extra[sans]?.getOrNull(font.ordinal - WidgetFont.ROUNDED.ordinal) ?: sans

    private val flip by lazy {{ intArrayOf({arr("clock_flip", ORDER)}) }}
    private val neon by lazy {{ intArrayOf({arr("clock_neon", ORDER)}) }}
    private val vertical by lazy {{ intArrayOf({arr("clock_vertical", ORDER)}) }}

    fun flip(font: WidgetFont): Int = flip[font.ordinal]
    fun neon(font: WidgetFont): Int = neon[font.ordinal]
    fun vertical(font: WidgetFont): Int = vertical[font.ordinal]

    /** One-line text layouts for the bundled faces (Glance text can't use app fonts). */
    val text: Map<WidgetFont, Int> by lazy {{
        mapOf(
{text},
        )
    }}
}}
'''
    with open(KT, "w", encoding="utf-8") as f:
        f.write(out)


if __name__ == "__main__":
    for fam in FAMILIES:
        for font in NEW_FONTS:
            from_sans(fam, font)
    for font in NEW_FONTS:
        text_layout(font)
    for font in ORDER:
        flip(font)
        neon(font)
        vertical(font)
    led()
    kotlin()
    print("ok")
